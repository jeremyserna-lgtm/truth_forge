@dataclass
class WorkProof:
    """Cryptographic proof of sovereign generation.

    This proves the atom was generated on sovereign hardware,
    not cloud infrastructure that could be compelled.

    Attributes:
        hardware_id: SHA256 of hardware identifiers (CPU, serial).
        timestamp: UTC timestamp of generation.
        nonce: Random value for uniqueness.
        hash: SHA256(hardware_id + timestamp + nonce + content_hash).
        signature: Optional GPG/age signature for non-repudiation.
    """

    hardware_id: str
    timestamp: str
    nonce: str
    content_hash: str
    work_hash: str
    signature: str | None = None

    @classmethod
    def generate(cls, content: str, sign: bool = False) -> WorkProof:
        """Generate a new Work Proof for content.

        Args:
            content: The content being attested.
            sign: Whether to generate a cryptographic signature.

        Returns:
            New WorkProof with valid hash.
        """
        # Hardware identification (obfuscated for privacy)
        hw_components = [
            platform.node(),
            platform.machine(),
            platform.processor(),
        ]
        hardware_id = hashlib.sha256("|".join(hw_components).encode()).hexdigest()[:16]

        timestamp = datetime.now(UTC).isoformat()
        nonce = uuid.uuid4().hex[:16]
        content_hash = hashlib.sha256(content.encode()).hexdigest()

        # Work hash proves the relationship
        work_input = f"{hardware_id}|{timestamp}|{nonce}|{content_hash}"
        work_hash = hashlib.sha256(work_input.encode()).hexdigest()

        return cls(
            hardware_id=hardware_id,
            timestamp=timestamp,
            nonce=nonce,
            content_hash=content_hash,
            work_hash=work_hash,
            signature=None,  # Signature requires key management
        )

    def verify(self, content: str) -> bool:
        """Verify the Work Proof is valid for content.

        Args:
            content: Content to verify against.

        Returns:
            True if proof is valid.
        """
        # Verify content hash
        expected_content_hash = hashlib.sha256(content.encode()).hexdigest()
        if expected_content_hash != self.content_hash:
            return False

        # Verify work hash
        work_input = f"{self.hardware_id}|{self.timestamp}|{self.nonce}|{self.content_hash}"
        expected_work_hash = hashlib.sha256(work_input.encode()).hexdigest()
        return expected_work_hash == self.work_hash

    def to_dict(self) -> dict[str, Any]:
        """Convert to dictionary."""
        return {
            "hardware_id": self.hardware_id,
            "timestamp": self.timestamp,
            "nonce": self.nonce,
            "content_hash": self.content_hash,
            "work_hash": self.work_hash,
            "signature": self.signature,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> WorkProof:
        """Create from dictionary."""
        return cls(**data)


