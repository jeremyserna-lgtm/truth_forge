@dataclass
class TruthAtom:
    """A cryptographically verified unit of sovereign knowledge.

    This is NOT an InsightAtom. This is a TRUTH ATOM - the output of
    the complete reciprocal learning loop including:
    1. Generation (seeing operation)
    2. Work Proof (cryptographic attestation)
    3. Validation (external validators)
    4. Surplus identification (novel value)

    Truth Atoms feed back into model behavior through:
    - Continuous LoRA updates
    - Prompt injection (few-shot examples)
    - Training data for next Genesis version

    Attributes:
        id: Unique identifier (UUID).
        content: The knowledge content.
        source_id: Where this atom originated.
        work_proof: Cryptographic proof of sovereign generation.
        surplus_vector: Description of novel value.
        cognitive_signature: Genesis architecture signature.
        verification_status: Current validation state.
        attestations: External validator attestations.
        created_at: When atom was created.
        validated_at: When atom was validated (if applicable).
        feedback_applied: Whether this atom has influenced model behavior.
        metadata: Additional context.
    """

    id: str = field(default_factory=lambda: str(uuid.uuid4()))
    content: str = ""
    source_id: str = ""
    work_proof: WorkProof | None = None
    surplus_vector: SurplusVector | None = None
    cognitive_signature: CognitiveSignature = field(default_factory=CognitiveSignature)
    verification_status: VerificationStatus = VerificationStatus.UNVERIFIED
    attestations: list[ValidatorAttestation] = field(default_factory=list)
    created_at: datetime = field(default_factory=lambda: datetime.now(UTC))
    validated_at: datetime | None = None
    feedback_applied: bool = False
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        """Generate work proof if not provided."""
        if self.content and self.work_proof is None:
            self.work_proof = WorkProof.generate(self.content)

    @classmethod
    def from_insight(
        cls,
        content: str,
        source_id: str,
        surplus_description: str,
        surplus_type: SurplusType = SurplusType.PATTERN,
        jeremy_arc_score: float = 0.0,
    ) -> TruthAtom:
        """Create a Truth Atom from a seeing insight.

        Args:
            content: The insight content.
            source_id: Source identifier.
            surplus_description: What makes this novel.
            surplus_type: Category of surplus.
            jeremy_arc_score: Current Jeremy Arc accuracy.

        Returns:
            New TruthAtom ready for validation.
        """
        return cls(
            content=content,
            source_id=source_id,
            work_proof=WorkProof.generate(content),
            surplus_vector=SurplusVector(
                surplus_type=surplus_type,
                description=surplus_description,
            ),
            cognitive_signature=CognitiveSignature(
                jeremy_arc_score=jeremy_arc_score,
            ),
        )

    def add_attestation(self, attestation: ValidatorAttestation) -> None:
        """Add a validator attestation.

        Updates verification status based on attestations.
        """
        self.attestations.append(attestation)
        self._update_verification_status()

    def _update_verification_status(self) -> None:
        """Update verification status based on attestations."""
        if not self.attestations:
            self.verification_status = VerificationStatus.UNVERIFIED
            return

        verdicts = [a.verdict for a in self.attestations]

        if all(v == "approved" for v in verdicts):
            self.verification_status = VerificationStatus.VALIDATED
            self.validated_at = datetime.now(UTC)
        elif all(v == "rejected" for v in verdicts):
            self.verification_status = VerificationStatus.REJECTED
        elif "approved" in verdicts and "rejected" in verdicts:
            self.verification_status = VerificationStatus.CONTESTED
        else:
            self.verification_status = VerificationStatus.PENDING

    def is_valid(self) -> bool:
        """Check if atom is valid (work proof verifies)."""
        if self.work_proof is None:
            return False
        return self.work_proof.verify(self.content)

    def is_validated(self) -> bool:
        """Check if atom has been externally validated."""
        return self.verification_status == VerificationStatus.VALIDATED

    def mark_feedback_applied(self) -> None:
        """Mark that this atom has influenced model behavior."""
        self.feedback_applied = True
        self.metadata["feedback_applied_at"] = datetime.now(UTC).isoformat()

    def to_dict(self) -> dict[str, Any]:
        """Convert to dictionary for storage."""
        return {
            "id": self.id,
            "content": self.content,
            "source_id": self.source_id,
            "work_proof": self.work_proof.to_dict() if self.work_proof else None,
            "surplus_vector": self.surplus_vector.to_dict() if self.surplus_vector else None,
            "cognitive_signature": self.cognitive_signature.to_dict(),
            "verification_status": self.verification_status.value,
            "attestations": [a.to_dict() for a in self.attestations],
            "created_at": self.created_at.isoformat(),
            "validated_at": self.validated_at.isoformat() if self.validated_at else None,
            "feedback_applied": self.feedback_applied,
            "metadata": self.metadata,
        }

    def to_json(self) -> str:
        """Convert to JSON string."""
        return json.dumps(self.to_dict(), indent=2)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> TruthAtom:
        """Create from dictionary."""
        work_proof = WorkProof.from_dict(data["work_proof"]) if data.get("work_proof") else None

        surplus_vector = None
        if data.get("surplus_vector"):
            sv = data["surplus_vector"]
            surplus_vector = SurplusVector(
                surplus_type=SurplusType(sv["surplus_type"]),
                description=sv["description"],
                sources=sv.get("sources", []),
                confidence=sv.get("confidence", 0.7),
                human_blindspot=sv.get("human_blindspot"),
            )

        sig_data = data.get("cognitive_signature", {})
        cognitive_signature = CognitiveSignature(
            cognitive_stage=sig_data.get("cognitive_stage", 5),
            training_layer=sig_data.get("training_layer", 5),
            mode=sig_data.get("mode", "mirror"),
            genesis_version=sig_data.get("genesis_version", "1.0.0"),
            jeremy_arc_score=sig_data.get("jeremy_arc_score", 0.0),
        )

        attestations = []
        for att_data in data.get("attestations", []):
            attestations.append(
                ValidatorAttestation(
                    validator=att_data["validator"],
                    verdict=att_data["verdict"],
                    reasoning=att_data["reasoning"],
                    timestamp=datetime.fromisoformat(att_data["timestamp"]),
                    confidence=att_data.get("confidence", 0.8),
                )
            )

        return cls(
            id=data["id"],
            content=data["content"],
            source_id=data["source_id"],
            work_proof=work_proof,
            surplus_vector=surplus_vector,
            cognitive_signature=cognitive_signature,
            verification_status=VerificationStatus(data.get("verification_status", "unverified")),
            attestations=attestations,
            created_at=datetime.fromisoformat(data["created_at"]),
            validated_at=datetime.fromisoformat(data["validated_at"])
            if data.get("validated_at")
            else None,
            feedback_applied=data.get("feedback_applied", False),
            metadata=data.get("metadata", {}),
        )


